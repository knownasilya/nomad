#!/usr/bin/env node
// Bundles the canvas (app/userland/app-stdlib/js/graph/phone.js, with ./view.js, the Notes graph and
// the Reader graph) into one HTML page for the phone, mobile/lib/canvasHtml.ts, which
// mobile/components/Canvas.tsx loads in a WebView for Notes and Reader. The file is committed (the
// phone app doesn't build it), so rerun this after changing the canvas or either graph:
//
//   npm run build:canvas

import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'app/userland/app-stdlib/js/graph/phone.js');
const out = path.join(root, 'mobile/lib/canvasHtml.ts');

const vite = await import('vite');
const result = await vite.build({
  root: path.join(root, 'app'),
  logLevel: 'warn',
  configFile: false,
  build: {
    write: false,
    minify: true,
    target: 'es2019',
    lib: { entry, formats: ['iife'], name: 'NomadCanvas', fileName: () => 'canvas.js' },
  },
  define: { 'process.env.NODE_ENV': '"production"' },
});
const outputs = Array.isArray(result) ? result : [result];
const chunk = outputs.flatMap((o) => o.output).find((o) => o.type === 'chunk');
if (!chunk) throw new Error('no bundle produced');
const js = chunk.code.replace(/<\/script/gi, '<\\/script');

// The canvas's own styles (desktop's, from app-stdlib), then the page. The colors come from the
// app's theme (phone.js applyTheme).
const graphCss = fs.readFileSync(path.join(root, 'app/userland/app-stdlib/css/graph.css'), 'utf8');
const css = `${graphCss}
html, body { margin: 0; height: 100%; overflow: hidden; background: var(--graph-bg); -webkit-text-size-adjust: 100%; }
body { font-family: -apple-system, BlinkMacSystemFont, system-ui, Roboto, 'Segoe UI', sans-serif; }
#canvas { position: fixed; inset: 0; }
:root { --graph-label-size: 12px; --graph-hub-label-size: 13px; }
`.replace(/<\/style/gi, '<\\/style');

const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no"><style>${css}</style></head><body><div id="canvas" class="graph-surface"></div><script>${js}</script></body></html>`;

fs.writeFileSync(
  out,
  `// Generated by scripts/build-canvas.mjs from app/userland/app-stdlib/js/graph/phone.js. Do not edit.\n` +
    `// The phone's canvas page for Notes and Reader (mobile/components/Canvas.tsx loads it in a WebView).\n` +
    `/* eslint-disable */\n` +
    `const html: string = ${JSON.stringify(html)}\n` +
    `export default html\n`
);
console.log(`wrote ${path.relative(root, out)} (${Math.round(html.length / 1024)} KB)`);
