#!/usr/bin/env node
// Bundles the Notes editor (app/userland/notes/js/mobile.js and ./editor/) into one HTML page for
// the phone, mobile/lib/noteEditorHtml.ts, which mobile/components/Notes.tsx loads in a WebView.
// The file is committed (the phone app doesn't build it), so rerun this after changing the editor:
//
//   npm run build:note-editor

import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'app/userland/notes/js/mobile.js');
const out = path.join(root, 'mobile/lib/noteEditorHtml.ts');

const vite = await import('vite');
const result = await vite.build({
  root: path.join(root, 'app'),
  logLevel: 'warn',
  configFile: false,
  build: {
    write: false,
    minify: true,
    target: 'es2019',
    lib: { entry, formats: ['iife'], name: 'NoteEditor', fileName: () => 'note-editor.js' },
  },
  define: { 'process.env.NODE_ENV': '"production"' },
});
const outputs = Array.isArray(result) ? result : [result];
const chunk = outputs.flatMap((o) => o.output).find((o) => o.type === 'chunk');
if (!chunk) throw new Error('no bundle produced');
const js = chunk.code.replace(/<\/script/gi, '<\\/script');

// The page's own styles. The colors come from the app's theme (mobile.js applyTheme).
const css = `
:root {
  --note-font: -apple-system, BlinkMacSystemFont, system-ui, Roboto, 'Segoe UI', sans-serif;
  --note-code-font: Menlo, 'Roboto Mono', monospace;
  --note-font-size: 16px;
  --note-width: 100%;
  --note-padding: 16px 18px 24px;
}
html, body { margin: 0; background: var(--note-page, #fff); color: var(--note-text, #1c1c22); -webkit-text-size-adjust: 100%; }
body { font-family: var(--note-font); }
#editor { min-height: 60vh; }
#mentions { margin: 0 18px 40px; padding-top: 12px; border-top: 1px solid var(--note-border, #e2e2e8); }
#mentions summary { display: flex; align-items: center; gap: 8px; padding: 4px 0; font-size: 12px; font-weight: 600; letter-spacing: 0.04em; text-transform: uppercase; color: var(--note-muted); list-style: none; -webkit-tap-highlight-color: transparent; }
#mentions summary::-webkit-details-marker { display: none; }
#mentions summary::before { content: ''; width: 5px; height: 5px; border: solid currentColor; border-width: 0 1.5px 1.5px 0; transform: rotate(-45deg); transition: transform 0.12s; }
#mentions details[open] summary::before { transform: rotate(45deg); }
#mentions details[open] summary { margin-bottom: 6px; }
#mentions .none { margin: 0; font-size: 13px; color: var(--note-muted); }
#mentions .list { max-height: 45vh; overflow-y: auto; overscroll-behavior: contain; }
#mentions .mention { display: block; width: 100%; padding: 8px 0; border: 0; background: none; text-align: left; font: inherit; }
#mentions .mention .title { display: block; font-size: 15px; font-weight: 600; color: var(--note-accent); }
#mentions .mention .snippet { display: block; overflow: hidden; font-size: 13px; color: var(--note-muted); text-overflow: ellipsis; white-space: nowrap; }
`;

const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"><style>${css}</style></head><body><div id="editor"></div><section id="mentions"></section><script>${js}</script></body></html>`;

fs.writeFileSync(
  out,
  `// Generated by scripts/build-note-editor.mjs from app/userland/notes/js/mobile.js. Do not edit.\n` +
    `// The phone's Notes editor page (mobile/components/Notes.tsx loads it in a WebView).\n` +
    `/* eslint-disable */\n` +
    `const html: string = ${JSON.stringify(html)}\n` +
    `export default html\n`
);
console.log(`wrote ${path.relative(root, out)} (${Math.round(html.length / 1024)} KB)`);
